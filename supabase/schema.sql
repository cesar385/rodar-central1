-- ---------- Seguridad (RLS) ----------
-- Usuarios con sesión (admin, operadores, conductores): acceso completo.
-- Público (pasajeros sin cuenta): solo lectura de servicios, pasarelas activas y avisos enviados;
-- todo lo demás pasa por las funciones seguras de abajo.
do $$
declare t text;
begin
  foreach t in array array['company','services','driver_plans','crews','drivers','driver_levels','operators','managers','customers','orders','promotions','notifications','reports','billing','api_keys','webhooks','payment_gateways','ratings']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "auth_all" on %I', t);
    execute format('create policy "auth_all" on %I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;
drop policy if exists "anon_services" on services;
create policy "anon_services" on services for select to anon using (status = 'active');
drop policy if exists "anon_gateways" on payment_gateways;
create policy "anon_gateways" on payment_gateways for select to anon using (active);
drop policy if exists "anon_notifications" on notifications;
create policy "anon_notifications" on notifications for select to anon using (sent_at is not null and audience in ('all','customers'));

-- ---------- Funciones para la app de pasajeros ----------
create or replace function public_company()
returns table(id int, name text, phone text, sos_phone text, currency text, zone jsonb)
language sql security definer set search_path = public as $$
  select id, name, phone, sos_phone, currency, zone from company order by id limit 1;
$$;

create or replace function point_in_zone(lat float8, lng float8, zone jsonb) returns bool
language plpgsql immutable as $$
declare n int := jsonb_array_length(coalesce(zone,'[]')); i int; j int; inside bool := false;
  yi float8; xi float8; yj float8; xj float8;
begin
  if n < 3 or lat is null then return true; end if;
  j := n - 1;
  for i in 0..n-1 loop
    yi := (zone->i->>0)::float8; xi := (zone->i->>1)::float8;
    yj := (zone->j->>0)::float8; xj := (zone->j->>1)::float8;
    if ((yi > lat) <> (yj > lat)) and (lng < (xj - xi) * (lat - yi) / (yj - yi) + xi) then inside := not inside; end if;
    j := i;
  end loop;
  return inside;
end $$;

create or replace function validate_promo(p_code text)
returns setof promotions language sql security definer set search_path = public as $$
  select * from promotions where code = upper(trim(p_code)) and active and type <> 'topup'
    and (valid_to is null or valid_to >= current_date) and (max_uses is null or used < max_uses) limit 1;
$$;

create or replace function create_order(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare o orders; z jsonb;
begin
  select zone into z from company order by id limit 1;
  if not point_in_zone((p->>'origin_lat')::float8, (p->>'origin_lng')::float8, z) then
    raise exception 'El origen está fuera del área de servicio.';
  end if;
  if coalesce(p->>'customer_phone','') = '' then raise exception 'Falta el teléfono'; end if;
  insert into orders (customer_name, customer_phone, customer_email, origin, origin_lat, origin_lng, destination, dest_lat, dest_lng,
    service_id, operator_id, status, source, price, distance_km, payment_method, coupon, notes, scheduled_at)
  values (p->>'customer_name', p->>'customer_phone', p->>'customer_email', p->>'origin', (p->>'origin_lat')::float8, (p->>'origin_lng')::float8,
    p->>'destination', (p->>'dest_lat')::float8, (p->>'dest_lng')::float8, nullif(p->>'service_id','')::uuid,
    case when auth.role() = 'authenticated' then nullif(p->>'operator_id','')::uuid end,
    'new', coalesce(p->>'source','web'), coalesce((p->>'price')::numeric,0), (p->>'distance_km')::numeric,
    coalesce(p->>'payment_method','cash'), nullif(p->>'coupon',''), p->>'notes', nullif(p->>'scheduled_at','')::timestamptz)
  returning * into o;
  insert into customers (name, phone, email, orders_count) values (o.customer_name, o.customer_phone, o.customer_email, 1)
    on conflict (phone) do update set name = coalesce(excluded.name, customers.name), orders_count = customers.orders_count + 1, updated_at = now();
  if o.coupon is not null then update promotions set used = used + 1 where code = o.coupon; end if;
  return jsonb_build_object('id', o.id, 'number', o.number);
end $$;

create or replace function track_order(p_id uuid)
returns table(id uuid, number bigint, status text, origin text, origin_lat float8, origin_lng float8, destination text,
  price numeric, rating int, driver_id uuid, driver_name text, driver_vehicle text, driver_plate text, driver_color text,
  driver_phone text, driver_lat float8, driver_lng float8)
language sql security definer set search_path = public as $$
  select o.id, o.number, o.status, o.origin, o.origin_lat, o.origin_lng, o.destination, o.price, o.rating, o.driver_id,
    d.name, d.vehicle, d.plate, d.color, d.phone, d.lat, d.lng
  from orders o left join drivers d on d.id = o.driver_id where o.id = p_id;
$$;

create or replace function cancel_order(p_id uuid) returns void
language sql security definer set search_path = public as $$
  update orders set status = 'cancelled', cancelled_at = now(), cancel_reason = 'pasajero'
  where id = p_id and status in ('new','assigned');
$$;

create or replace function rate_order(p_id uuid, p_rating int) returns void
language plpgsql security definer set search_path = public as $$
declare d uuid;
begin
  update orders set rating = least(5, greatest(1, p_rating)) where id = p_id and status = 'completed' and rating is null returning driver_id into d;
  if d is not null then
    update drivers set rating = (select round(avg(rating)::numeric, 2) from orders where driver_id = d and rating is not null) where id = d;
  end if;
end $$;

grant execute on function public_company, validate_promo, create_order, track_order, cancel_order, rate_order to anon, authenticated;

